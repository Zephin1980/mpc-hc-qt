#!/usr/bin/env python3
"""Generate src/Commands.h from MPC-HC's resource.h so the Linux port keeps
the exact same command names (ID_PLAY_PLAYPAUSE etc.) as the Windows build."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "src/mpc-hc/resource.h").read_text(encoding="utf-8", errors="replace")
ids = [m.group(1) for m in re.finditer(r"#define\s+(ID_[A-Z0-9_]+)\s+\d+", src)]
out = ["// GENERATED by tools/gen_commands.py -- do not edit.",
       "#pragma once", "", "namespace Cmd {", "enum Id : int {"]
out += [f"    {n}," for n in ids]
out += ["    COUNT", "};", "}", ""]
(root / "linux/src/Commands.h").write_text("\n".join(out))
print(f"wrote {len(ids)} command ids")
